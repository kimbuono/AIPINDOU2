BRANDS = {
    "artkal": ARTKAL,
    "perler": PERLER,
    "hama":   HAMA,
}

def get_palette(brand: str) -> List[BeadColor]:
    """Return the colour list for *brand* (case-insensitive)."""
    key = brand.lower().strip()
    if key not in BRANDS:
        raise ValueError(f"Unknown brand '{brand}'. Available: {list(BRANDS.keys())}")
    return BRANDS[key]

def palette_names() -> List[str]:
    """Return list of supported brand names."""
    return list(BRANDS.keys())
